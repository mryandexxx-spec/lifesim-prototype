export function gardenModelState(sku,view){
 const variants=OF_GARDEN_ASSETS[sku];if(!variants)return null;
 const stage=Number.isInteger(view?.stage)?Math.min(3,Math.max(0,view.stage)):0;
 const wet=(view?.waterRemaining??0)>0;
 const harvested=stage===3&&variants.harvested&&view?.harvestedAt!=null;
 const variant=harvested?'harvested':stage===3?(wet?'wet':'new'):['seed','sprout','growing'][stage];
 return {variant,wet,wetSoil:wet&&variant!=='wet'};
}
