import test from 'node:test';
import assert from 'node:assert/strict';
import {newHousehold,loadHousehold,tickHousehold,chooseResidentAction,residentAutonomousChoice} from '../src/household.js';
import {hireCareer,newCareerSystem} from '../src/career-state.js';
import {plannedCareerShift} from '../src/career-scheduler.js';
import {SHOP_MAX_CREDITS} from '../src/furniture-shop.js';
import {progressCareerWork,residentAwayAtWork,residentUnavailableForHome,
  requestCareerDeparture,arriveCareerPortal,finishCareerReturn,skipCareerShift,
  residentWorkStatus} from '../src/career-work.js';

const json=value=>JSON.parse(JSON.stringify(value));
const fresh=()=>newHousehold('2026-11-16');
const job=(root,id,career,at=root.minutes)=>{
  root.careerSystem=hireCareer(root.careerSystem,id,career,at);
  return root.careerSystem.byResident[id];
};
test('W1-B.3a full Monday loop: notice, depart, absent, return, exactly one pay receipt',()=>{
  const root=fresh(),initial=root.shop.credits;
  job(root,'alex','editorial');
  const notice=tickHousehold(root,45);
  assert.ok(notice.some(x=>x.type==='reminder'));
  assert.equal(root.shop.credits,initial);
  assert.equal(root.careerSystem.byResident.alex.currentShift.phase,'pending');
  tickHousehold(root,15);
  assert.equal(root.careerSystem.byResident.alex.currentShift.phase,'departing');
  assert.equal(residentUnavailableForHome(root,'alex'),true);
  assert.equal(chooseResidentAction(root,'fridge',false,'alex'),false);
  assert.equal(residentAutonomousChoice(root,'alex'),null);
  assert.equal(arriveCareerPortal(root,'alex',root.minutes),true);
  assert.equal(residentAwayAtWork(root,'alex'),true);
  assert.match(residentWorkStatus(root,'alex').label,/На работе/);
  const otherEnergy=root.otherSim.needs.energy;
  const events=tickHousehold(root,480);
  assert.ok(events.some(x=>x.type==='salary'));
  assert.equal(root.shop.credits,initial+112);
  assert.equal(root.careerSystem.byResident.alex.currentShift.phase,'returning');
  assert.equal(root.careerSystem.settlementIds.length,1);
  assert.equal(root.otherSim.minutes,root.minutes);
  assert.ok(root.otherSim.needs.energy<otherEnergy,'Mira continues independent life');
  tickHousehold(root,15);
  assert.equal(root.shop.credits,initial+112,'repeated tick cannot pay twice');
  assert.equal(finishCareerReturn(root,'alex'),true);
  assert.equal(residentAwayAtWork(root,'alex'),false);
  assert.equal(root.careerSystem.byResident.alex.lastShift.salary,112);
  assert.equal(root.careerSystem.byResident.alex.currentShift,null);
});
test('W1-B.3a Safari reload midshift and after payout preserve once-only ledger',()=>{
  let root=fresh(),original=root.shop.credits;
  job(root,'mira','editorial',480);
  root.minutes=540;root.otherSim.minutes=540;
  progressCareerWork(root,539.9,540);
  assert.equal(requestCareerDeparture(root,'mira',540).ok,false,
    'Automatic departure already began');
  assert.equal(arriveCareerPortal(root,'mira',540),true);
  tickHousehold(root,200);
  assert.equal(root.shop.credits,original);
  const restored=loadHousehold(json(root),'2030-09-08');
  assert.equal(restored.careerSystem.byResident.mira.currentShift.phase,'working');
  assert.equal(restored.careerSystem.byResident.mira.currentShift.departedAt,540);
  assert.equal(residentAwayAtWork(restored,'mira'),true);
  tickHousehold(restored,280);
  assert.equal(restored.shop.credits,original+112);
  const once=json(restored);
  let again=loadHousehold(once);
  tickHousehold(again,1);
  assert.equal(again.shop.credits,original+112);
  assert.equal(again.careerSystem.settlementIds.length,1);
  assert.equal(finishCareerReturn(again,'mira'),true);
  again=loadHousehold(json(again));
  tickHousehold(again,2);
  assert.equal(again.shop.credits,original+112);
  assert.equal(again.careerSystem.byResident.mira.lastShift.salary,112);
});
test('W1-B.3a two independent workers earn different rates into one household wallet',()=>{
  const root=fresh(),start=root.shop.credits;
  job(root,'alex','editorial');job(root,'mira','business-center');
  tickHousehold(root,60);
  assert.equal(arriveCareerPortal(root,'alex',root.minutes),true);
  assert.equal(arriveCareerPortal(root,'mira',root.minutes),true);
  tickHousehold(root,480);
  assert.equal(root.shop.credits,start+112+144);
  assert.equal(root.careerSystem.settlementIds.length,2);
  assert.equal(finishCareerReturn(root,'alex'),true);
  assert.equal(finishCareerReturn(root,'mira'),true);
  assert.equal(root.careerSystem.byResident.alex.lastShift.salary,112);
  assert.equal(root.careerSystem.byResident.mira.lastShift.salary,144);
});
test('W1-B.3a overnight shifts pay after next midnight and skip nonworking days',()=>{
  const root=fresh();
  job(root,'mira','civic-service');
  const shift=plannedCareerShift(root.calendar,root.careerSystem.byResident.mira,2);
  assert.equal(shift.start,2*1440+1200);
  assert.equal(shift.end,3*1440+240);
  root.minutes=shift.start-10;root.otherSim.minutes=root.minutes;
  tickHousehold(root,10);
  assert.equal(root.careerSystem.byResident.mira.currentShift.phase,'departing');
  arriveCareerPortal(root,'mira',root.minutes);
  tickHousehold(root,239);
  assert.equal(root.shop.credits,5000,'No early salary on calendar day change');
  tickHousehold(root,241);
  assert.equal(root.shop.credits,5000+152);
  assert.equal(root.careerSystem.settlementIds.length,1);
  assert.equal(plannedCareerShift(root.calendar,root.careerSystem.byResident.mira,0),null);
});
test('W1-B.3a late starts earn only minutes worked; missed shifts and manual skip pay nothing',()=>{
  const root=fresh();job(root,'alex','editorial');
  root.minutes=540;root.otherSim.minutes=540;
  const actor=root;
  actor.action={id:'bed',phase:'walking',automatic:false,elapsed:0};
  const blocked=progressCareerWork(root,539,550);
  assert.ok(blocked.some(x=>x.type==='late'));
  assert.equal(root.careerSystem.byResident.alex.currentShift.phase,'pending');
  actor.action=null;
  progressCareerWork(root,550,570);
  assert.equal(root.careerSystem.byResident.alex.currentShift.phase,'departing');
  assert.equal(arriveCareerPortal(root,'alex',570),true);
  root.minutes=570;root.otherSim.minutes=570;
  tickHousehold(root,450);
  assert.equal(root.shop.credits,5000+105);
  assert.equal(root.careerSystem.byResident.alex.lastShift.lateMinutes,30);
  const second=fresh();job(second,'alex','editorial');
  progressCareerWork(second,480,538);
  assert.equal(skipCareerShift(second,'alex'),true);
  assert.equal(second.careerSystem.byResident.alex.lastShift.outcome,'missed');
  assert.deepEqual(progressCareerWork(second,538,1020),[]);
  assert.equal(second.shop.credits,5000);
  const third=fresh();job(third,'alex','editorial');
  const missed=progressCareerWork(third,480,1020);
  assert.ok(missed.some(x=>x.type==='missed'));
  assert.equal(third.shop.credits,5000);
});
test('W1-B.3a early manual exit at -15, pause, corrupted midshift and wallet cap',()=>{
  const root=fresh();job(root,'alex','editorial');
  progressCareerWork(root,480,525);
  assert.equal(requestCareerDeparture(root,'alex',525).ok,true);
  assert.equal(arriveCareerPortal(root,'alex',525),true);
  assert.equal(root.careerSystem.byResident.alex.currentShift.departedAt,540);
  const before=JSON.stringify(root);
  root.paused=true;
  tickHousehold(root,500);
  assert.equal(JSON.stringify(root),JSON.stringify({...JSON.parse(before),paused:true}));
  root.paused=false;
  root.shop.credits=SHOP_MAX_CREDITS-4;
  tickHousehold(root,540);
  assert.equal(root.shop.credits,SHOP_MAX_CREDITS);
  const saved=json(root);
  assert.equal(loadHousehold(saved).shop.credits,SHOP_MAX_CREDITS);
  saved.careerSystem.byResident.alex.currentShift.id='tampered';
  const malformed=loadHousehold(saved);
  assert.equal(malformed.careerSystem.byResident.alex.currentShift,null);
  assert.equal(malformed.shop.credits,SHOP_MAX_CREDITS);
});
