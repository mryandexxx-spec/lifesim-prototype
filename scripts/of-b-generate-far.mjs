/** Branch-only offline LOD generation. Exact high GLBs remain immutable.
 * glTF Transform / meshoptimizer simplify; no runtime decoder/dependency. */
import {NodeIO} from '@gltf-transform/core';
import {ALL_EXTENSIONS} from '@gltf-transform/extensions';
import {weld,simplify} from '@gltf-transform/functions';
import {MeshoptSimplifier} from 'meshoptimizer';
import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import assert from 'node:assert/strict';
import {OF_VEGETATION_ENTRIES} from '../src/of-vegetation-assets.js';
await MeshoptSimplifier.ready;
const io=new NodeIO().registerExtensions(ALL_EXTENSIONS);
const dir='assets/furniture/of-r2/',manifest={};
const hash=b=>createHash('sha256').update(b).digest('hex');
function counts(doc){const prims=doc.getRoot().listMeshes().flatMap(m=>m.listPrimitives());return {triangles:prims.reduce((n,p)=>n+(p.getIndices()?.getCount()??p.getAttribute('POSITION').getCount())/3,0),materials:doc.getRoot().listMaterials().length,primitives:prims.length};}
for(const e of OF_VEGETATION_ENTRIES){
 const src=dir+e.sku+'.glb',dst=dir+e.sku+'-far.glb';
 const bytes=readFileSync(src);assert.equal(hash(bytes),e.sha256);
 const doc=await io.read(src);const before=counts(doc);assert.equal(before.triangles,e.triangles);
 // Retain all material primitives, don't weld across attributes or merge nodes.
 // Limit geometric error to 4% of primitive extent; inspect real images before shipping.
 await doc.transform(weld(),simplify({simplifier:MeshoptSimplifier,ratio:.25,error:.04}));
 await io.write(dst,doc);
 const after=counts(await io.read(dst));const data=readFileSync(dst);
 assert.equal(after.materials,before.materials,e.sku+' materials');assert.equal(after.primitives,before.primitives,e.sku+' primitives');
 assert.ok(after.triangles>0&&after.triangles<=before.triangles,e.sku+' triangles');
 manifest[e.sku]={file:e.sku+'-far.glb',sha256:hash(data),bytes:data.length,triangles:after.triangles,materials:after.materials,sourceSha256:e.sha256};
 console.log(e.sku,before.triangles,'->',after.triangles,bytes.length,'->',data.length);
}
const source=Object.freeze(manifest);
writeFileSync('src/of-vegetation-far-data.js','/** Generated by scripts/of-b-generate-far.mjs from exact approved R2 GLBs. */\nexport const OF_FAR_LODS=Object.freeze('+JSON.stringify(source,null,2)+');\n');
mkdirSync('artifacts/of-b',{recursive:true});writeFileSync('artifacts/of-b/far-manifest.json',JSON.stringify(source,null,2));
